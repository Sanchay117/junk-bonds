// The film draws with the game's own artwork and stylesheet, so the two cannot drift apart.
// Copies ../web/src/art.jsx to src/art.tsx (as React) and ../web/src/style.css to src/web.css.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, '..', 'web', 'src');

const art = readFileSync(join(web, 'art.jsx'), 'utf8')
  .replace(/\bclass=/g, 'className=')
  .replace(/stroke-width=/g, 'strokeWidth=')
  .replace(/stroke-linecap=/g, 'strokeLinecap=')
  .replace(/stroke-linejoin=/g, 'strokeLinejoin=')
  .replace(/text-anchor=/g, 'textAnchor=');
writeFileSync(join(root, 'src', 'art.tsx'), '// @ts-nocheck\n// Generated by scripts/sync.mjs from web/src/art.jsx. Do not edit.\n' + art);
writeFileSync(join(root, 'src', 'web.css'), readFileSync(join(web, 'style.css'), 'utf8'));
console.log('synced art.tsx and web.css');
